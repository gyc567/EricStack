#!/usr/bin/env python3
"""regenerate-wiki-index.py — Auto-generate .loopx/wiki/index.md from .loopx/skills/.

Scans every SKILL.md, extracts frontmatter (name, description, triggers),
and writes a categorized Markdown index.

Usage:
  python3 .loopx/bin/regenerate-wiki-index.py           # write to .loopx/wiki/index.md
  python3 .loopx/bin/regenerate-wiki-index.py --stdout  # print to stdout
  python3 .loopx/bin/regenerate-wiki-index.py --check   # exit non-zero if index is stale
"""
import argparse
import re
import sys
from pathlib import Path


def parse_frontmatter(text):
    """Extract YAML-ish frontmatter into a dict."""
    m = re.match(r'^---\n(.*?)\n---\n', text, re.DOTALL)
    if not m:
        return None
    fm = m.group(1)
    result = {'name': None, 'description': None, 'triggers': [], 'allowed_tools': []}
    current_key = None
    for line in fm.split('\n'):
        if line.startswith('name:'):
            result['name'] = line[5:].strip().strip('"').strip("'")
        elif line.startswith('description:'):
            result['description'] = line[12:].strip().strip('"').strip("'")
        elif line.startswith('triggers:'):
            current_key = 'triggers'
        elif line.startswith('allowed-tools:'):
            current_key = 'allowed_tools'
        elif current_key and line.startswith('  - '):
            val = line[4:].strip().strip('"').strip("'")
            if current_key in result:
                result[current_key].append(val)
        else:
            current_key = None
    return result


def categorize(path):
    """Determine the kind based on directory, not name (some skills lack prefix)."""
    s = str(path).replace('\\', '/')
    if '/erics-process/' in s:
        return 'process'
    if '/erics-ability/' in s:
        return 'ability'
    if '/erics-loop-router/' in s:
        return 'router'
    return 'other'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--skills-dir', default='.loopx/skills',
                        help='Path to skills directory')
    parser.add_argument('--output', default='.loopx/wiki/index.md',
                        help='Output path')
    parser.add_argument('--stdout', action='store_true', help='Print to stdout')
    parser.add_argument('--check', action='store_true',
                        help='Exit non-zero if output is stale (used in CI)')
    args = parser.parse_args()

    skills_dir = Path(args.skills_dir)
    output = Path(args.output)

    if not skills_dir.exists():
        print(f'ERROR: skills dir not found: {skills_dir}', file=sys.stderr)
        sys.exit(2)

    skills = {'process': [], 'ability': [], 'router': [], 'other': []}
    for skill_md in sorted(skills_dir.rglob('SKILL.md')):
        if '/.omc/' in str(skill_md):
            continue
        try:
            text = skill_md.read_text()
        except Exception as e:
            print(f'WARN: cannot read {skill_md}: {e}', file=sys.stderr)
            continue
        fm = parse_frontmatter(text)
        if not fm or not fm['name']:
            continue
        kind = categorize(skill_md)
        skills[kind].append((skill_md, fm))

    total = sum(len(v) for v in skills.values())
    lines = []
    lines.append('# Skills Index')
    lines.append('')
    lines.append('> Auto-generated by `regenerate-wiki-index.py`')
    lines.append('> Do not edit manually — run the regenerator after adding/removing skills.')
    lines.append('')
    n_proc = len(skills['process'])
    n_abi = len(skills['ability'])
    n_rou = len(skills['router'])
    lines.append(
        f'Total: **{total} skills** ({n_proc} process + {n_abi} ability + {n_rou} router)'
    )
    lines.append('')

    sections = [
        ('process', 'Process Skills (Discipline / 纪律)'),
        ('ability', 'Ability Skills (Action / 能力)'),
        ('router', 'Special Skills (Router / 路由)'),
    ]
    for kind, title in sections:
        if not skills[kind]:
            continue
        lines.append(f'## {title}')
        lines.append('')
        for path, fm in skills[kind]:
            name = fm['name']
            desc = fm['description'] or '(no description)'
            triggers = fm['triggers'][:5]
            lines.append(f'### `{name}`')
            lines.append('')
            lines.append(desc)
            lines.append('')
            if triggers:
                lines.append('**Triggers:** ' + ', '.join(f'`{t}`' for t in triggers))
                lines.append('')
            try:
                rel = path.relative_to(skills_dir.parent)
                lines.append(f'*File:* `.loopx/{rel}`')
            except ValueError:
                lines.append(f'*File:* `{path}`')
            lines.append('')

    lines.append('---')
    lines.append('')
    lines.append('Run `/erics-loop-router` to invoke the router, or use a trigger keyword directly.')
    lines.append('')

    content = '\n'.join(lines)

    if args.stdout:
        print(content)
        return

    if args.check:
        if not output.exists():
            print(f'STALE: {output} does not exist')
            sys.exit(1)
        existing = output.read_text()
        norm = lambda s: re.sub(r'>\s*Auto-generated by[^\n]*', '', s).strip()
        if norm(existing) != norm(content):
            print(f'STALE: {output} differs from generated content')
            print('Run: python3 .loopx/bin/regenerate-wiki-index.py')
            sys.exit(1)
        print(f'OK: {output} is up to date')
        return

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content)
    print(
        f'Wrote {output} ({total} skills: '
        f'{n_proc} process, {n_abi} ability, {n_rou} router)'
    )


if __name__ == '__main__':
    main()
